import { sql } from "drizzle-orm";
import { integer, pgTable, primaryKey, text, timestamp, uniqueIndex, uuid } from "drizzle-orm/pg-core";

/**
 * Data model for purchases (PRD section 17, reduced to what Cooked+ needs).
 * Store as little personal data as possible: no emails, no names. Restore
 * checks the email against the payment provider instead of storing it.
 */

/** Anonymous player, created only when someone starts checkout or restores. */
export const players = pgTable("players", {
  id: uuid("id").primaryKey().default(sql`gen_random_uuid()`),
  /** "13to17" or "adult". Under-13s cannot reach checkout, so no row is ever made for them. */
  ageBand: text("age_band"),
  createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
  deletedAt: timestamp("deleted_at", { withTimezone: true }),
});

export const purchases = pgTable(
  "purchases",
  {
    id: uuid("id").primaryKey().default(sql`gen_random_uuid()`),
    playerId: uuid("player_id").references(() => players.id),
    productKey: text("product_key").notNull(),
    provider: text("provider").notNull(),
    providerPaymentId: text("provider_payment_id").notNull(),
    amount: integer("amount").notNull(),
    currency: text("currency").notNull(),
    /** "succeeded" or "refunded". */
    status: text("status").notNull(),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
    updatedAt: timestamp("updated_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [uniqueIndex("purchases_provider_payment_uq").on(t.provider, t.providerPaymentId)],
);

export const entitlements = pgTable(
  "entitlements",
  {
    id: uuid("id").primaryKey().default(sql`gen_random_uuid()`),
    playerId: uuid("player_id").notNull().references(() => players.id),
    key: text("key").notNull(),
    sourceType: text("source_type").notNull(),
    sourceId: uuid("source_id").notNull(),
    startsAt: timestamp("starts_at", { withTimezone: true }).notNull().defaultNow(),
    endsAt: timestamp("ends_at", { withTimezone: true }),
    revokedAt: timestamp("revoked_at", { withTimezone: true }),
  },
  (t) => [uniqueIndex("entitlements_player_key_source_uq").on(t.playerId, t.key, t.sourceId)],
);

/** Idempotency log: each provider event is processed once, even when retried. */
export const webhookEvents = pgTable(
  "webhook_events",
  {
    provider: text("provider").notNull(),
    eventId: text("event_id").notNull(),
    eventType: text("event_type").notNull(),
    receivedAt: timestamp("received_at", { withTimezone: true }).notNull().defaultNow(),
    processedAt: timestamp("processed_at", { withTimezone: true }),
  },
  (t) => [primaryKey({ columns: [t.provider, t.eventId] })],
);

/**
 * Daily leaderboards (Daily, Blitz, One Life). One row per player per board per
 * day, keeping their best. Handles are generated by the server, never typed, so
 * there is nothing to moderate. Rows older than 30 days are deleted by a cron.
 */
export const leaderboardEntries = pgTable(
  "leaderboard_entries",
  {
    id: uuid("id").primaryKey().default(sql`gen_random_uuid()`),
    playerId: uuid("player_id").notNull().references(() => players.id),
    board: text("board").notNull(),
    day: text("day").notNull(),
    score: integer("score").notNull(),
    ghost: text("ghost").notNull(),
    character: text("character").notNull(),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
    updatedAt: timestamp("updated_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [uniqueIndex("leaderboard_player_board_day_uq").on(t.playerId, t.board, t.day)],
);

/** Public handle per player, generated on first leaderboard post. */
export const handles = pgTable("handles", {
  playerId: uuid("player_id").primaryKey().references(() => players.id),
  handle: text("handle").notNull().unique(),
  createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
});
